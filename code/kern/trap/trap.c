// lab3: timer interrupt dispatch
void interrupt_handler(struct trapframe *tf) {
    uintptr_t cause = tf->cause & ~((uintptr_t)1 << (sizeof(uintptr_t) * 8 - 1));
    switch (cause) {
    case IRQ_U_SOFT:
        cprintf("User software interrupt\n");
        break;
    case IRQ_S_SOFT:
        cprintf("Supervisor software interrupt\n");
        break;
    case IRQ_M_SOFT:
        cprintf("Machine software interrupt\n");
        break;
    case IRQ_U_TIMER:
        cprintf("User timer interrupt\n");
        break;
    case IRQ_S_TIMER:
        clock_set_next_event();
        ticks++;
        if (current != NULL) {
            current->need_resched = 1;
        }
        break;
    case IRQ_M_TIMER:
        cprintf("Machine timer interrupt\n");
        break;
    case IRQ_U_EXT:
        cprintf("User external interrupt\n");
        break;
    case IRQ_S_EXT:
        cprintf("Supervisor external interrupt\n");
        break;
    case IRQ_M_EXT:
        cprintf("Machine external interrupt\n");
        break;
    default:
        cprintf("Unknown interrupt: cause %d\n", (int)cause);
        print_trapframe(tf);
        break;
    }
}

// lab5 function1 2411870
void exception_handler(struct trapframe *tf)
{
    if (tf->cause == CAUSE_USER_ECALL)
    {
        tf->epc += 4;
        syscall();
        return;
    }
    if (!trap_in_kernel(tf))
    {
        if (tf->cause == CAUSE_STORE_PAGE_FAULT && current != NULL)
        {
            int ret = cow_resolve(current->mm, tf->tval);
            if (ret == 0)
            {
                return; // Retry the original store with the corrected mapping.
            }
            if (ret == -E_NO_MEM)
            {
                do_exit(ret);
            }
        }
        cprintf("user exception: cause %lu, epc %p, address %p\n",
                tf->cause, (void *)tf->epc, (void *)tf->tval);
        do_exit(-E_KILLED);
    }
    print_trapframe(tf);
    panic("unexpected supervisor exception");
}

static inline void trap_dispatch(struct trapframe *tf)
{
    if ((intptr_t)tf->cause < 0)
    {
        // interrupts
        interrupt_handler(tf);
    }
    else
    {
        // exceptions
        exception_handler(tf);
    }
}

/* *
 * trap - handles or dispatches an exception/interrupt. if and when trap() returns,
 * the code in kern/trap/trapentry.S restores the old CPU state saved in the
 * trapframe and then uses the sret instruction to return from the exception.
 * */
void trap(struct trapframe *tf)
{
    // dispatch based on what type of trap occurred
    //    cputs("some trap");
    if (current == NULL)
    {
        trap_dispatch(tf);
    }
    else
    {
        struct trapframe *otf = current->tf;
        current->tf = tf;

        bool in_kernel = trap_in_kernel(tf);

        trap_dispatch(tf);

        current->tf = otf;
        if (!in_kernel)
        {
            if (current->flags & PF_EXITING)
            {
                do_exit(-E_KILLED);
            }
            if (current->need_resched)
            {
                schedule();
            }
        }
    }
}
